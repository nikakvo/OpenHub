    @Override
    protected void initView(Bundle savedInstanceState) {
        super.initView(savedInstanceState);
        setToolbarBackEnable();
        if (pendingFiles == null) pendingFiles = new ArrayList<>();
        if (deletedAssetIds == null) deletedAssetIds = new ArrayList<>();
        if (renamedAssets == null) renamedAssets = new HashMap<>();
        if (savedInstanceState == null) {
            if (!pendingFiles.isEmpty()) dirty = true;
            fill(release);
        }
        updateTitle();
        updateTagStatus();
        updateLatestOption();
        updateButtons();
        renderFiles();
        loadInitialData();
    }

    @Override
    protected void onPostCreate(@Nullable Bundle savedInstanceState) {
        super.onPostCreate(savedInstanceState);
        // after the views restored their state, so a rotation does not count as an edit
        setupListeners();
        updateTagStatus();
    }


    private void updateButtons() {
        if (isPublished()) {
            secondaryBn.setVisibility(View.GONE);
            primaryBn.setText(R.string.release_update);
        } else {
            secondaryBn.setVisibility(View.VISIBLE);
            primaryBn.setText(R.string.release_publish);
        }
    }

    private void onPrimaryClick() {
        save(!isPublished());
    }

    private void onSecondaryClick() {
        save(false);
    }

    /**
     * @param publish publish now (or, with new files, as soon as they are uploaded)
     */
    private void save(final boolean publish) {
        if (saving) return;
        final String tag = tagText();
        if (tag.isEmpty()) {
            tagLayout.setError(getString(R.string.release_tag_required));
            tagEdit.requestFocus();
            return;
        }
        if (tag.contains(" ")) {
            tagLayout.setError(getString(R.string.release_tag_no_spaces));
            tagEdit.requestFocus();
            return;
        }
        String duplicate = duplicateFileName();
        if (duplicate != null) {
            showErrorToast(getString(R.string.upload_name_exists, duplicate));
            return;
        }

        final boolean preRelease = preReleaseCheck.isChecked();
        final boolean wasDraftOrNew = !isPublished();
        final boolean hasFiles = !pendingFiles.isEmpty();
        // GitHub cannot make a draft or a pre-release Latest
        final String makeLatest = preRelease ? "false" : (latestCheck.isChecked() ? "true" : "false");
        final boolean publishNow = publish && wasDraftOrNew && !hasFiles;
        final boolean publishAfterUpload = publish && wasDraftOrNew && hasFiles;

        final Map<String, Object> body = new HashMap<>();
        body.put("tag_name", tag);
        body.put("name", textOf(titleEdit).trim());
        body.put("body", textOf(bodyEdit));
        body.put("prerelease", preRelease);
        if (isNewTag() && target != null) body.put("target_commitish", target);
        if (isCreate()) {
            body.put("draft", !publishNow);
        } else if (publishNow) {
            body.put("draft", false);
        }
        if (publishNow) {
            body.put("make_latest", makeLatest);
        } else if (isPublished() && !wasLatest && latestCheck.isChecked() && !preRelease) {
            body.put("make_latest", "true");
        }

        final boolean created = isCreate();
        final String releaseId = created ? null : release.getId();
        final ArrayList<String> deletes = new ArrayList<>(deletedAssetIds);
        final HashMap<String, String> renames = new HashMap<>(renamedAssets);
        for (String id : deletes) renames.remove(id);
        final ArrayList<UploadItem> files = new ArrayList<>(pendingFiles);
        final boolean checksums = checksumsCheck != null && checksumsCheck.isChecked();
        UploadService.setChecksumsWanted(this, checksums);

        saving = true;
        invalidateBack();
        primaryBn.setEnabled(false);
        secondaryBn.setEnabled(false);
        showProgressDialog(getString(R.string.release_saving));
        background(() -> {
            ReleaseService service = releaseService();
            Release saved = created
                    ? GitHubApi.call(service.createRelease(owner, repo, body))
                    : GitHubApi.call(service.updateRelease(owner, repo, releaseId, body));
            if (saved == null) throw new IOException("Empty answer");
            // From here on the release exists: a retry must edit it, not create another.
            runOnUiThread(() -> adopt(saved));
            for (String id : deletes) {
                GitHubApi.call(service.deleteAsset(owner, repo, id));
            }
            for (Map.Entry<String, String> rename : renames.entrySet()) {
                Map<String, Object> change = new HashMap<>();
                change.put("name", rename.getValue());
                GitHubApi.call(service.updateAsset(owner, repo, rename.getKey(), change));
            }
            return saved;
        }, (Release saved) -> {
            dismissProgressDialog();
            saving = false;
            ReleaseChanges.markChanged();
            if (!files.isEmpty()) {
                UploadService.start(this, owner, repo, saved, files, publishAfterUpload,
                        publishAfterUpload ? makeLatest : null, checksums);
                pendingFiles.clear();
                showInfoToast(publishAfterUpload
                        ? getResources().getQuantityString(R.plurals.upload_started_then_publish,
                        files.size(), files.size())
                        : getResources().getQuantityString(R.plurals.upload_started,
                        files.size(), files.size()));
            } else {
                // files deleted or renamed: the SHA256SUMS file follows
                if (checksums && (!deletes.isEmpty() || !renames.isEmpty())) {
                    UploadService.writeChecksums(this, owner, repo, saved);
                }
                showSuccessToast(getString(publishNow ? R.string.release_published_short
                        : saved.isDraft() ? R.string.release_draft_saved : R.string.release_updated));
            }
            dirty = false;
            setResult(RESULT_OK, new Intent().putExtra("release", saved));
            if (created) ReleaseInfoActivity.show(this, owner, repo, saved);
            finish();
        }, error -> {
            dismissProgressDialog();
            saving = false;
            primaryBn.setEnabled(true);
            secondaryBn.setEnabled(true);
            invalidateBack();
            if (release != null) {
                // part of the save went through: show what GitHub has now
                freshLoaded = false;
                loadInitialData();
            }
        });
    }

    /** The release now exists on GitHub (also after a partly failed save). */
    private void adopt(@NonNull Release saved) {
        boolean wasCreate = release == null;
        release = saved;
        freshLoaded = true;
        deletedAssetIds.clear();
        renamedAssets.clear();
        if (wasCreate) {
            ReleaseChanges.markChanged();
            updateTitle();
            updateButtons();
        }
    }

    // ---------------------------------------------------------------------------------
    // Back / unsaved changes
    // ---------------------------------------------------------------------------------

    @Override
    protected boolean interceptsBack() {
        return super.interceptsBack() || (dirty && !saving);
    }

    @Override
    protected void handleBack() {
        super.handleBack();
        if (!dirty || saving) return;
        new AlertDialog.Builder(this)
                .setTitle(R.string.release_discard_title)
                .setMessage(R.string.release_discard_message)
                .setPositiveButton(R.string.release_discard, (d, w) -> {
                    for (UploadItem item : pendingFiles) {
                        ContentFiles.releaseReadAccess(this, Uri.parse(item.getUri()));
                    }
                    dirty = false;
                    invalidateBack();
                    finish();
                })
                .setNegativeButton(R.string.release_keep_editing, null)
                .show();
    }


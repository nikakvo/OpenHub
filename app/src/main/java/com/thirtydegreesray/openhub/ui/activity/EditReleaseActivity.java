    protected void onDestroy() {
        disposables.clear();
        if (notesEditor != null) notesEditor.dispose();
        super.onDestroy();
    }

    private boolean isCreate() {
        return release == null;
    }

    private boolean isPublished() {
        return release != null && !release.isDraft();
    }

    private void updateTitle() {
        String subTitle = owner + "/" + repo;
        if (isCreate()) {
            setToolbarTitle(getString(R.string.release_new), subTitle);
        } else {
            setToolbarTitle(getString(release.isDraft() ? R.string.release_edit_draft : R.string.release_edit),
                    subTitle);
        }
    }

    private void fill(@Nullable Release source) {
        filling = true;
        if (source == null) {
            latestCheck.setChecked(true);
        } else {
            tagEdit.setText(source.getTagName());
            titleEdit.setText(source.getName());
            bodyEdit.setText(source.getBody());
            preReleaseCheck.setChecked(source.isPreRelease());
            latestCheck.setChecked(!source.isPreRelease());
            if (!StringUtils.isBlank(source.getTargetCommitish())) target = source.getTargetCommitish();
        }
        filling = false;
    }

    private void setupListeners() {
        TextWatcher watcher = new TextWatcher() {
            @Override
            public void beforeTextChanged(CharSequence s, int start, int count, int after) {
            }

            @Override
            public void onTextChanged(CharSequence s, int start, int before, int count) {
            }

            @Override
            public void afterTextChanged(Editable s) {
                markDirty();
            }
        };
        titleEdit.addTextChangedListener(watcher);
        bodyEdit.addTextChangedListener(watcher);
        tagEdit.addTextChangedListener(new TextWatcher() {
            @Override
            public void beforeTextChanged(CharSequence s, int start, int count, int after) {
            }

            @Override
            public void onTextChanged(CharSequence s, int start, int before, int count) {
            }

            @Override
            public void afterTextChanged(Editable s) {
                tagLayout.setErrorEnabled(false);
                markDirty();
                updateTagStatus();
            }
        });
        preReleaseCheck.setOnCheckedChangeListener((v, checked) -> {
            markDirty();
            updateLatestOption();
        });
        latestCheck.setOnCheckedChangeListener((v, checked) -> markDirty());
    }

    private void markDirty() {
        if (filling || dirty) return;
        dirty = true;
        invalidateBack();
    }

    // ---------------------------------------------------------------------------------
    // Loading
    // ---------------------------------------------------------------------------------

    private void loadInitialData() {
        if (defaultBranch == null) {
            background(() -> GitHubApi.call(GitHubApi.service(RepoService.class)
                    .getRepoInfo(true, owner, repo)), (Repository repository) -> {
                defaultBranch = repository.getDefaultBranch();
                if (target == null) target = defaultBranch;
                updateTagStatus();
            }, null);
        }
        if (tags == null) {
            background(() -> {
                ArrayList<String> names = new ArrayList<>();
                List<Branch> list = GitHubApi.call(releaseService().getTags(true, owner, repo, 1));
                if (list != null) for (Branch branch : list) names.add(branch.getName());
                return names;
            }, (ArrayList<String> names) -> {
                tags = names;
                updateTagStatus();
            }, null);
        }
        if (release != null && !freshLoaded) {
            // edit the current text, not the copy the previous screen had
            final String id = release.getId();
            showLoading();
            background(() -> GitHubApi.call(releaseService().getRelease(true, owner, repo, id)),
                    (Release fresh) -> {
                        hideLoading();
                        freshLoaded = true;
                        boolean draftChanged = fresh.isDraft() != release.isDraft();
                        release = fresh;
                        if (!dirty) fill(fresh);
                        updateTitle();
                        updateButtons();
                        renderFiles();
                        if (draftChanged) updateLatestOption();
                        loadLatestState();
                    }, error -> hideLoading());
        } else if (isPublished()) {
            loadLatestState();
        }
    }

    private void loadLatestState() {
        if (!isPublished()) return;
        final String id = release.getId();
        background(() -> {
            try {
                Release latest = GitHubApi.call(releaseService().getLatestRelease(true, owner, repo));
                return latest != null && id.equals(latest.getId());
            } catch (GitHubApi.ApiException e) {
                if (e.code == 404) return false;
                throw e;
            }
        }, (Boolean latest) -> {
            wasLatest = latest;
            updateLatestOption();
        }, null);
    }

    // ---------------------------------------------------------------------------------
    // Tag, target, latest
    // ---------------------------------------------------------------------------------

    @NonNull
    private String tagText() {
        return tagEdit.getText() == null ? "" : tagEdit.getText().toString().trim();
    }

    private boolean isNewTag() {
        String tag = tagText();
        return !tag.isEmpty() && tags != null && !tags.contains(tag);
    }

    private void updateTagStatus() {
        String tag = tagText();
        if (tag.isEmpty() || tags == null) {
            tagStatus.setVisibility(View.GONE);
            targetRow.setVisibility(View.GONE);
            return;
        }
        tagStatus.setVisibility(View.VISIBLE);
        if (isNewTag()) {
            tagStatus.setText(R.string.release_tag_new);
            targetRow.setVisibility(View.VISIBLE);
            targetText.setText(target == null ? "…" : target);
        } else {
            tagStatus.setText(R.string.release_tag_existing);
            targetRow.setVisibility(View.GONE);
        }
    }

    private void updateLatestOption() {
        boolean preRelease = preReleaseCheck.isChecked();
        filling = true;
        if (preRelease) {
            latestCheck.setChecked(false);
            latestCheck.setEnabled(false);
            latestHint.setText(R.string.release_latest_prerelease_hint);
            latestHint.setVisibility(View.VISIBLE);
        } else if (isPublished() && wasLatest) {
            latestCheck.setChecked(true);
            latestCheck.setEnabled(false);
            latestHint.setText(R.string.release_latest_current_hint);
            latestHint.setVisibility(View.VISIBLE);
        } else {
            latestCheck.setEnabled(true);
            if (isPublished() && !dirty) latestCheck.setChecked(false);
            latestHint.setVisibility(View.GONE);
        }
        filling = false;
    }

    private void chooseTag() {
        if (tags == null) {
            showInfoToast(getString(R.string.release_tags_loading));
            return;
        }
        if (tags.isEmpty()) {
            showInfoToast(getString(R.string.release_no_tags));
            return;
        }
        String[] items = tags.toArray(new String[0]);
        new AlertDialog.Builder(this)
                .setTitle(R.string.release_choose_tag)
                .setItems(items, (dialog, which) -> {
                    tagEdit.setText(items[which]);
                    tagEdit.setSelection(items[which].length());
                })
                .setNegativeButton(R.string.cancel, null)
                .show();
    }

    private void chooseTarget() {
        showLoading();
        background(() -> {
            ArrayList<String> names = new ArrayList<>();
            List<Branch> list = GitHubApi.call(releaseService().getBranches(true, owner, repo, 1));
            if (list != null) for (Branch branch : list) names.add(branch.getName());
            return names;
        }, (ArrayList<String> names) -> {
            hideLoading();
            if (names.isEmpty()) return;
            String[] items = names.toArray(new String[0]);
            int checked = target == null ? -1 : names.indexOf(target);
            new AlertDialog.Builder(this)
                    .setTitle(R.string.release_target)
                    .setSingleChoiceItems(items, checked, (dialog, which) -> {
                        target = items[which];
                        markDirty();
                        updateTagStatus();
                        dialog.dismiss();
                    })
                    .setNegativeButton(R.string.cancel, null)
                    .show();
        }, error -> hideLoading());
    }

    // ---------------------------------------------------------------------------------
    // Notes
    // ---------------------------------------------------------------------------------

    private void generateNotes() {
        String tag = tagText();
        if (tag.isEmpty()) {
            tagLayout.setError(getString(R.string.release_tag_required_for_notes));
            tagEdit.requestFocus();
            return;
        }
        Map<String, Object> body = new HashMap<>();
        body.put("tag_name", tag);
        if (isNewTag() && target != null) body.put("target_commitish", target);
        showProgressDialog(getString(R.string.please_wait));
        background(() -> GitHubApi.call(releaseService().generateNotes(owner, repo, body)),
                (GeneratedNotes notes) -> {
                    dismissProgressDialog();
                    applyNotes(notes);
                }, error -> dismissProgressDialog());
    }

    private void applyNotes(@NonNull GeneratedNotes notes) {
        Runnable apply = () -> {
            notesEditor.showWrite();
            bodyEdit.setText(notes.getBody());
            if (StringUtils.isBlank(textOf(titleEdit)) && !StringUtils.isBlank(notes.getName())) {
                titleEdit.setText(notes.getName());
            }
        };
        if (StringUtils.isBlank(textOf(bodyEdit))) {
            apply.run();
        } else {
            new AlertDialog.Builder(this)
                    .setTitle(R.string.release_generate_notes)
                    .setMessage(R.string.release_replace_notes)
                    .setPositiveButton(R.string.release_replace, (d, w) -> apply.run())
                    .setNegativeButton(R.string.cancel, null)
                    .show();
        }
    }

    @NonNull
    private static String textOf(@NonNull TextInputEditText edit) {
        return edit.getText() == null ? "" : edit.getText().toString();
    }

    @Override
    protected void onActivityResult(int requestCode, int resultCode, @Nullable Intent data) {
        super.onActivityResult(requestCode, resultCode, data);
        if (requestCode == MARKDOWN_EDITOR_REQUEST_CODE && resultCode == RESULT_OK && data != null) {
            String text = data.getStringExtra("text");
            notesEditor.showWrite();
            bodyEdit.setText(text);
            if (text != null) bodyEdit.setSelection(text.length());
        }
    }


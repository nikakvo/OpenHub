    private void renderFiles() {
        filesList.removeAllViews();
        LayoutInflater inflater = LayoutInflater.from(this);
        int count = 0;
        if (release != null && release.getAssets() != null) {
            for (ReleaseAsset asset : release.getAssets()) {
                filesList.addView(existingRow(inflater, asset));
                if (!deletedAssetIds.contains(asset.getId())) count++;
            }
        }
        for (UploadItem item : pendingFiles) {
            filesList.addView(pendingRow(inflater, item));
            count++;
        }
        filesTitle.setText(count == 0 ? getString(R.string.release_files)
                : getString(R.string.release_files_count, count));
    }

    @NonNull
    private View existingRow(@NonNull LayoutInflater inflater, @NonNull ReleaseAsset asset) {
        View row = inflater.inflate(R.layout.layout_item_release_asset, filesList, false);
        TextView name = row.findViewById(R.id.asset_name);
        TextView meta = row.findViewById(R.id.asset_meta);
        ImageView action = row.findViewById(R.id.asset_action_bn);
        row.findViewById(R.id.asset_download_bn).setVisibility(View.GONE);
        action.setVisibility(View.VISIBLE);

        boolean deleted = deletedAssetIds.contains(asset.getId());
        String newName = renamedAssets.get(asset.getId());
        name.setText(newName != null ? newName : asset.getName());
        String size = StringUtils.getSizeString(asset.getSize());
        if (deleted) {
            name.setPaintFlags(name.getPaintFlags() | Paint.STRIKE_THRU_TEXT_FLAG);
            meta.setText(getString(R.string.release_file_will_be_deleted));
            row.setAlpha(0.5f);
            action.setImageResource(R.drawable.ic_undo);
            action.setContentDescription(getString(R.string.release_keep_file));
        } else {
            meta.setText(newName != null ? size + " · " + getString(R.string.release_file_renamed, asset.getName())
                    : size);
            action.setImageResource(R.drawable.ic_close);
            action.setContentDescription(getString(R.string.release_remove_file));
            View.OnClickListener rename = v -> TextInputDialog.show(this, R.string.release_rename_file,
                    R.string.release_file_name, name.getText().toString(), true, text -> {
                        String clean = ContentFiles.assetName(text);
                        if (clean.equals(asset.getName())) renamedAssets.remove(asset.getId());
                        else renamedAssets.put(asset.getId(), clean);
                        markDirty();
                        renderFiles();
                    });
            View edit = row.findViewById(R.id.asset_edit_bn);
            edit.setVisibility(View.VISIBLE);
            edit.setOnClickListener(rename);
            row.setOnClickListener(rename);
        }
        action.setOnClickListener(v -> {
            if (deleted) deletedAssetIds.remove(asset.getId());
            else deletedAssetIds.add(asset.getId());
            markDirty();
            renderFiles();
        });
        return row;
    }

    @NonNull
    private View pendingRow(@NonNull LayoutInflater inflater, @NonNull UploadItem item) {
        View row = inflater.inflate(R.layout.layout_item_release_asset, filesList, false);
        ((ImageView) row.findViewById(R.id.asset_icon)).setImageResource(R.drawable.ic_upload);
        ((TextView) row.findViewById(R.id.asset_name)).setText(item.getName());
        String size = item.getSize() >= 0 ? StringUtils.getSizeString(item.getSize()) + " · " : "";
        ((TextView) row.findViewById(R.id.asset_meta)).setText(size + getString(R.string.release_file_new));
        row.findViewById(R.id.asset_download_bn).setVisibility(View.GONE);
        ImageView action = row.findViewById(R.id.asset_action_bn);
        action.setVisibility(View.VISIBLE);
        action.setImageResource(R.drawable.ic_close);
        action.setContentDescription(getString(R.string.release_remove_file));
        action.setOnClickListener(v -> {
            pendingFiles.remove(item);
            ContentFiles.releaseReadAccess(this, Uri.parse(item.getUri()));
            markDirty();
            renderFiles();
        });
        View.OnClickListener rename = v -> TextInputDialog.show(this, R.string.release_rename_file,
                R.string.release_file_name, item.getName(), true, text -> {
                    item.setName(ContentFiles.assetName(text));
                    markDirty();
                    renderFiles();
                });
        View edit = row.findViewById(R.id.asset_edit_bn);
        edit.setVisibility(View.VISIBLE);
        edit.setOnClickListener(rename);
        row.setOnClickListener(rename);
        return row;
    }

    /** Name of the first file whose final name is used twice, or null. */
    @Nullable
    private String duplicateFileName() {
        Set<String> names = new HashSet<>();
        if (release != null && release.getAssets() != null) {
            for (ReleaseAsset asset : release.getAssets()) {
                if (deletedAssetIds.contains(asset.getId())) continue;
                String name = renamedAssets.containsKey(asset.getId())
                        ? renamedAssets.get(asset.getId()) : asset.getName();
                if (!names.add(name)) return name;
            }
        }
        for (UploadItem item : pendingFiles) {
            if (!names.add(item.getName())) return item.getName();
        }
        return null;
    }

